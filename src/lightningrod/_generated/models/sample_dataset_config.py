T = TypeVar("T", bound="SampleDatasetConfig")


@_attrs_define
class SampleDatasetConfig:
    r"""Configuration for loading a dataset of samples from the sample database.

    Fields:
        id: Dataset ID used to fetch samples from the DB.
        sample_ids: The specific sample IDs to load from that dataset.
        prompt_template: Optional custom prompt format. If None, uses the default section-based layout
            (QUESTION / CONTEXT / ANSWER FORMAT / CLOSE DATE).
        multiple_choice_options: Advanced override for multi-choice datasets where the option map can't be
            derived from the samples themselves. By default, options are auto-extracted from the
            question text (which works for any question generated by our standard pipeline, since
            options are embedded as `option_0: ...` lines). Only set this if samples were imported
            from an external source (e.g. Metaculus) where the question text is plain prose and
            options were stored separately.

            Example (standard pipeline — leave as None):
                "What will the Fed decide by March 2025?\noption_0: Rate increase\noption_1: No change"
                → options auto-extracted, no override needed.

            Example (external import — override required):
                question text: "What will the Fed decide by March 2025?" (no option lines)
                multiple_choice_options='{"option_0": "Rate increase", "option_1": "No change", "option_2": "Rate cut"}'

        Attributes:
            id (str):
            sample_ids (list[str]):
            prompt_template (None | str | Unset):
            multiple_choice_options (None | str | Unset):
    """

    id: str
    sample_ids: list[str]
    prompt_template: None | str | Unset = UNSET
    multiple_choice_options: None | str | Unset = UNSET
